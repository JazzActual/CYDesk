"""Convert TrueType fonts into TFT_eSPI "smooth fonts" (VLW format) as C headers.

TFT_eSPI can draw anti-aliased text from a VLW font stored in flash. The usual
way to make one is a Processing sketch; this script does the same with
FreeType, so fonts can be regenerated with one command:

    python3 -m pip install freetype-py      # once
    python3 tools/make_fonts.py

It writes one header per entry in FONTS into src/fonts/. Each font is
rendered at one exact pixel size, so every size used on screen needs its own
entry. Large sizes only include the characters they need, to save flash.

VLW layout (all numbers are 32-bit big-endian), as read by TFT_eSPI's
Smooth_font.cpp:
  header:  glyph count, version, size, 0, ascent, descent
  glyphs:  unicode, height, width, xAdvance, dY (top above baseline),
           dX (left offset), 0          -- one 28-byte record per glyph
  bitmaps: width*height bytes of 0..255 coverage per glyph, in the same order
"""
from pathlib import Path
import struct

import freetype

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets" / "fonts"
OUT_DIR = ROOT / "src" / "fonts"

ASCII = "".join(chr(c) for c in range(0x20, 0x7F))  # space .. ~
DEGREE = "°"

# (C name, font file, pixel size, characters)
FONTS = [
    ("rajdhani_16", "Rajdhani-SemiBold.ttf", 16, ASCII + DEGREE),  # date, place, labels
    ("rajdhani_24", "Rajdhani-SemiBold.ttf", 24, ASCII + DEGREE),  # greeting, AM/PM
    ("rajdhani_40", "Rajdhani-SemiBold.ttf", 40, "0123456789-" + DEGREE + "FC "),  # temperature
    ("rajdhani_56", "Rajdhani-SemiBold.ttf", 56, "0123456789:- "),  # clock digits
]


def be32(value: int) -> bytes:
    return struct.pack(">i", value)


def make_vlw(font_file: Path, size: int, chars: str) -> bytes:
    face = freetype.Face(str(font_file))
    face.set_pixel_sizes(0, size)

    def glyph(ch):
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bmp = g.bitmap
        rows, width, pitch = bmp.rows, bmp.width, bmp.pitch
        data = bytes(bmp.buffer[r * pitch + c] for r in range(rows) for c in range(width))
        return {
            "code": ord(ch),
            "height": rows,
            "width": width,
            "advance": (g.advance.x + 32) >> 6,  # 26.6 fixed point -> pixels
            "dy": g.bitmap_top,
            "dx": g.bitmap_left,
            "bitmap": data,
        }

    # Ascent/descent the way Processing measures them: top of "d", bottom of "p".
    d, p = glyph("d"), glyph("p")
    ascent = d["dy"]
    descent = p["height"] - p["dy"]

    glyphs = [glyph(ch) for ch in sorted(set(chars))]
    out = bytearray()
    out += be32(len(glyphs)) + be32(11) + be32(size) + be32(0) + be32(ascent) + be32(descent)
    for g in glyphs:
        for field in ("code", "height", "width", "advance", "dy", "dx"):
            out += be32(g[field])
        out += be32(0)
    for g in glyphs:
        out += g["bitmap"]
    return bytes(out)


def write_header(name: str, source: str, size: int, chars: str, data: bytes) -> Path:
    lines = [
        f"// Generated by tools/make_fonts.py -- do not edit by hand.",
        f"// {source} at {size} px, {len(set(chars))} characters, {len(data)} bytes.",
        "#pragma once",
        "#include <pgmspace.h>",
        "",
        f"const uint8_t {name}[] PROGMEM = {{",
    ]
    for i in range(0, len(data), 20):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i : i + 20]) + ",")
    lines.append("};")
    path = OUT_DIR / f"{name}.h"
    path.write_text("\n".join(lines) + "\n")
    return path


def main():
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, file, size, chars in FONTS:
        data = make_vlw(FONT_DIR / file, size, chars)
        path = write_header(name, file, size, chars, data)
        print(f"{path.relative_to(ROOT)}: {len(data)} bytes")


if __name__ == "__main__":
    main()
